using System.Windows;
using System.Windows.Controls;

namespace Apteka;

public partial class HelpWindow : Window
{
    public HelpWindow(string initial)
    {
        InitializeComponent();
        ThemeManager.Style(this);
        BuildGuide();
        Tabs.SelectedIndex = initial == "about" ? 1 : 0;
    }

    void BuildGuide()
    {
        // Each text is ONE string literal on purpose: it is also the translation key (see Translations.cs).
        void H(string text) => GuidePanel.Children.Add(new TextBlock
        {
            Text = Loc.T(text), FontSize = 16, FontWeight = FontWeights.Bold, Margin = new Thickness(0, 12, 0, 4)
        });
        void P(string text) => GuidePanel.Children.Add(new TextBlock
        {
            Text = Loc.T(text), TextWrapping = TextWrapping.Wrap, Margin = new Thickness(0, 0, 0, 6)
        });
        void B(string text) => GuidePanel.Children.Add(new TextBlock
        {
            Text = "•  " + Loc.T(text), TextWrapping = TextWrapping.Wrap, Margin = new Thickness(0, 0, 0, 4)
        });

        H("1. Вход в систему");
        P("При запуске открывается окно входа. Введите логин и пароль, выданные администратором, или нажмите «Войти как гость» для просмотра каталога без права редактирования. Язык интерфейса можно выбрать прямо в окне входа.");
        P("Тестовые учётные записи: admin / admin123 (Администратор), pharm / pharm123 (Фармацевт).");
        P("Пароли хранятся в виде SHA-256-хеша, поэтому восстановить исходный пароль нельзя — его можно только сменить.");

        H("2. Роли и права");
        B("Администратор — полный доступ ко всем таблицам, ручной ввод SQL в отчётах, аналитика.");
        B("Фармацевт — CRUD по пациентам, заказам, рецептам; чтение остального; аналитика.");
        B("Гость — только чтение каталога лекарств и связанных справочников; аналитика.");

        H("3. Справочники");
        P("Меню «Справочники» содержит словарные таблицы, а подменю «Связующие таблицы (M:N)» — таблицы связей. При выборе таблицы открывается страница с таблицей данных:");
        B("«Добавить» — форма добавления с проверкой обязательных полей и значениями по умолчанию.");
        B("«Изменить» — открывает выбранную запись (или двойной щелчок по строке).");
        B("«Удалить» — удаление с подтверждением; если запись используется в других таблицах, программа объяснит, что нужно сделать.");
        B("Поле «Поиск» фильтрует данные по всем столбцам одновременно.");
        B("Столбцы можно сортировать щелчком по заголовку.");
        B("Внешние ключи показаны как читаемые названия (ФИО, название лекарства и т. д.).");

        H("4. Документы");
        B("«Оформление заказа» — выберите пациента и лекарство, укажите количество и нажмите «Оформить заказ». Если на складе меньше лекарства, чем вы запросили, программа покажет, сколько его в наличии.");
        B("«Журналы документов» — заказы, рецепты, заявки и поставки.");
        B("«Отчёты и запросы» — 20 шаблонов; ручной ввод SELECT доступен только администратору.");
        B("«Экспорт текущей таблицы в CSV» — сохраняет открытую таблицу (разделитель «;», UTF-8 BOM).");

        H("5. Аналитика");
        P("Раздел показывает дашборд из четырёх диаграмм: столбчатые диаграммы (количество лекарств и средняя цена по категориям), круговая диаграмма (заказы по статусам) и линейный график (заказы по дням). Фильтр по датам действует на график «Заказы по дням». Можно включить автообновление (каждые 5 секунд) и экспортировать весь дашборд в PNG.");

        H("6. Справка и Разное");
        B("«Справка → Руководство пользователя» — этот текст.");
        B("«Справка → О программе» — информация о версии.");
        B("«Разное → Настройка» — тема (Classic 3D / Light / Dark / Blue), размер шрифта и язык интерфейса (русский, English, Français, العربية). Сохраняется в %AppData%\\Apteka\\settings.json.");
        B("«Разное → Сменить пароль» — старый пароль проверяется по хешу, новый должен быть ≥ 4 символов.");

        H("7. Журнал действий");
        P("Все входы, изменения данных, ошибки и экспорт записываются в таблицу ActionLog (на русском языке).");

        H("8. Если что-то пошло не так");
        P("Вместо технических сообщений базы данных программа показывает понятное объяснение: что произошло и что нужно сделать (например, «Недостаточно лекарства на складе»). Для непредвиденных ошибок внизу сообщения приводятся технические подробности — покажите их администратору.");
    }
}
